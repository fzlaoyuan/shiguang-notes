const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('notesAPI',{
  load:()=>ipcRenderer.invoke('load'),
  change:action=>ipcRenderer.invoke('change',action),
  setLock:(id,password)=>ipcRenderer.invoke('note-set-lock',id,password),
  unlock:(id,password)=>ipcRenderer.invoke('note-unlock',id,password),
  relock:id=>ipcRenderer.invoke('note-relock',id),
  lockNow:id=>ipcRenderer.invoke('note-lock-now',id),
  removeLock:(id,password)=>ipcRenderer.invoke('note-remove-lock',id,password),
  lockReady:(token,message)=>ipcRenderer.send('note-lock-ready',token,message),
  onBeforeLock:fn=>ipcRenderer.on('note-before-lock',(_,id,token)=>fn(id,token)),
  onLockFinished:fn=>ipcRenderer.on('note-lock-finished',()=>fn()),
  exportBackup:()=>ipcRenderer.invoke('export-backup'),
  importBackup:()=>ipcRenderer.invoke('import-backup'),
  exportNote:(id,format)=>ipcRenderer.invoke('export-note',id,format),
  openData:()=>ipcRenderer.invoke('open-data'),
  openContact:key=>ipcRenderer.invoke('open-contact',key),
  float:id=>ipcRenderer.invoke('float',id),
  window:action=>ipcRenderer.invoke('window',action),
  readyClose:()=>ipcRenderer.send('ready-close'),
  onFlush:fn=>{ipcRenderer.on('flush',fn);},
  onData:fn=>{ipcRenderer.on('data',(_,data)=>fn(data));},
  onNew:fn=>{ipcRenderer.on('new-note',fn);}
});
